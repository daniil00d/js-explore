// Эталонные флаги к лабе «Подбери флаги».
//
// 1. --print-bytecode печатает байткод всего, что компилируется, включая внутренности
//    Node: вывод получается на десятки тысяч строк. Отсекает лишнее второй флаг,
//    --print-bytecode-filter, он принимает имя функции (можно с *).
//
// 2. --always-turbofan снимает порог горячести: каждая функция отправляется
//    в TurboFan при первой возможности. Полезно, чтобы посмотреть на оптимизированный
//    код небольшой функции, но мерить производительность под этим флагом бессмысленно —
//    оптимизация перестаёт быть избирательной.
//
// 3. --max-opt задаёт верхний уровень компиляции: 0 — только интерпретатор,
//    1 — ещё и Sparkplug, 2 — Maglev, 3 — TurboFan. Ноль оставляет spin в байткоде
//    навсегда. Похожий, но более грубый способ — --jitless: он выключает и JIT,
//    и всё, что требует исполняемой памяти.
//
// 4. --trace-gc печатает по строке на каждую сборку мусора: тип, размеры до и после,
//    длительность паузы.
//
// 5. --max-semi-space-size=1 сжимает молодое поколение до одного мегабайта.
//    Объекты в нём кончаются быстрее, scavenger срабатывает чаще. Этим приёмом
//    удобно воспроизводить проблемы с GC, не выделяя гигабайты.
//
// Полезно заметить разницу между флагами двух видов: --print-bytecode и --trace-gc
// только наблюдают, а --always-turbofan, --max-opt и --max-semi-space-size меняют
// поведение движка. Первые можно оставлять в диагностике смело, вторые — нельзя.

