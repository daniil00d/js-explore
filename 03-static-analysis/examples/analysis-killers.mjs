// Код, на котором любой анализатор обязан сдаться — и что именно он теряет.
//
// Каждый раздел устроен одинаково: сначала анализ из этого же каталога даёт
// ответ, потом тот же код выполняется, и ответы сравниваются. Там, где анализ
// уверенно ошибается, это видно сразу; там, где он отвечает «не знаю», видно,
// сколько информации при этом потеряно.
//
// Запуск: node 03-static-analysis/examples/analysis-killers.mjs

import * as acorn from 'acorn';
import { note, raw, section, table } from '../../tools/format.mjs';
import { allBindings, analyzeScopes } from './scope.mjs';

/** Неиспользуемые привязки по нашему scope-анализу — как это делает линтер. */
function unusedBindings(code) {
  const ast = acorn.parse(code, { ecmaVersion: 'latest', sourceType: 'module', locations: true });
  const { scopes } = analyzeScopes(ast);
  return allBindings(scopes)
    .filter((binding) => ['const', 'let', 'var'].includes(binding.kind))
    .filter((binding) => binding.reads === 0)
    .map((binding) => binding.name);
}

const show = (value) => (typeof value === 'string' ? JSON.stringify(value) : String(value));

section('eval: одна строка отменяет весь анализ имён');

const withEval = `export function render(template) {
  const secret = 'ключ-42';
  const unused = 'этого действительно никто не читает';
  return eval(template);
}`;

withEval.split('\n').forEach((text, index) => raw(`  ${String(index + 1).padStart(2)} | ${text}`));

const evalUnused = unusedBindings(withEval);
const render = new Function(`${withEval.replace('export ', '')}
return render;`)();

table(
  ['что говорит анализ', 'что происходит при запуске'],
  [
    [`переменные без чтений: ${evalUnused.join(', ')}`, `eval('secret') вернул ${show(render('secret'))}`],
    ['значит, их можно удалить или переименовать', 'после такой правки — ReferenceError'],
  ],
);

note(
  'Обе привязки анализ назвал непрочитанными, и про одну он прав, а про другую —',
  'нет. `eval` получает строку в рантайме и читает из неё любое имя, до которого',
  'дотягивается область видимости. Никакой анализ дерева этого не увидит: строка',
  'может прийти из сети.',
  '',
  'Поэтому прямой `eval` — это не «плохой стиль», а конструкция, после которой',
  'корректный анализатор обязан считать, что прочитано и перезаписано может быть',
  'всё, что видно в этой точке. Практические последствия ровно два: минификатор',
  'перестаёт переименовывать локальные имена в такой функции, а линтер перестаёт',
  'верить своему `no-unused-vars`.',
  '',
  'Косвенный вызов — `(0, eval)(code)` или `globalThis.eval(code)` — работает только',
  'с глобальной областью видимости, и это уже терпимо: локальные имена он не видит.',
  'Разница между прямым и косвенным вызовом описана в спецификации отдельно, и',
  'инструменты её различают.',
);

section('with: имя перестаёт быть именем');

// `with` в модулях и строгом режиме запрещён, поэтому код собирается через
// new Function — там он выполняется в нестрогом режиме, как в старом скрипте.
const withStatement = `function total(order) {
  let sum = 0;
  with (order) {
    sum = price * count;
  }
  return sum;
}`;

withStatement.split('\n').forEach((text, index) => raw(`  ${String(index + 1).padStart(2)} | ${text}`));

const total = new Function(`${withStatement}
return total;`)();

const scopeVerdict = (() => {
  // Разбираем как скрипт: в модуле `with` — синтаксическая ошибка.
  const ast = acorn.parse(withStatement, { ecmaVersion: 'latest', sourceType: 'script', locations: true });
  const { unresolved } = analyzeScopes(ast);
  return unresolved.map((entry) => entry.name);
})();

table(
  ['что говорит анализ', 'что происходит при запуске'],
  [
    [
      `имена ниоткуда: ${scopeVerdict.join(', ')}`,
      `total({ price: 10, count: 3 }) = ${total({ price: 10, count: 3 })}`,
    ],
    [
      'sum — локальная переменная, ей и присваивают',
      `но при наличии order.sum вернулось ${total({ price: 10, count: 3, sum: 999 })} вместо 30`,
    ],
  ],
);

note(
  '`price` и `count` анализ считает глобальными: в дереве их объявлений нет. На',
  'самом деле они — свойства объекта, который придёт в рантайме, и какие у него',
  'свойства, заранее неизвестно.',
  '',
  'Хуже второе. Внутри `with` даже `sum` перестаёт быть надёжным: у объекта',
  'оказалось своё свойство `sum`, присваивание ушло в объект, локальная переменная',
  'осталась нулём — и функция вернула 0 вместо 30. То есть `with` ломает не только',
  'разрешение неизвестных имён, но и разрешение известных.',
  '',
  'Именно поэтому строгий режим `with` запретил, а модули строгие всегда. Это',
  'первый в языке случай, когда конструкцию убрали в основном ради анализируемости.',
);

section('obj[key]: точка, где теряется почти всё');

const registry = {
  create: () => 'создано',
  remove: () => 'удалено',
};

const dynamicKey = (name) => registry[name]?.() ?? 'нет обработчика';

table(
  ['выражение', 'что известно анализу', 'что получится при запуске'],
  [
    ['registry.create()', 'свойство create, функция известна', registry.create()],
    ['registry[name]()', 'свойство неизвестно, значение ⊤', dynamicKey('create')],
    ['registry[name]()', 'то же самое', dynamicKey('remove')],
    ['registry[name]()', 'то же самое', dynamicKey('archive')],
  ],
);

note(
  'Разница между `obj.key` и `obj[key]` для анализатора примерно как между',
  'известным и неизвестным адресом. В первом случае можно проследить, что именно',
  'читается, переименовать свойство, доказать, что метод существует. Во втором —',
  'нельзя ничего: ключ появится в рантайме.',
  '',
  'Отсюда правило Closure Compiler, которое кажется драконовским, пока не поймёшь',
  'причину: в режиме продвинутой минификации нельзя обращаться к одному и тому же',
  'свойству и через точку, и через строку. Компилятор переименовывает свойства,',
  'а строку в `obj["create"]` переименовать не может — он не знает, что это то же',
  'самое свойство.',
  '',
  'То же самое, но мягче, происходит в TypeScript: `obj[key]` без сужения типа ключа',
  'даёт индексный доступ, про который система типов знает гораздо меньше, чем про',
  'обращение по имени.',
);

section('Геттеры: чтение свойства — это вызов');

let reads = 0;
const point = {
  get x() {
    reads += 1;
    return reads; // значение меняется от чтения к чтению
  },
};

const first = point.x;
const second = point.x;

table(
  ['предположение', 'верно?', 'проверка'],
  [
    ['чтение свойства не имеет побочных эффектов', 'нет', `после двух чтений reads = ${reads}`],
    ['point.x + point.x равно 2 * point.x', 'нет', `получилось ${first} и ${second}`],
    ['порядок чтений можно менять', 'нет', 'значение зависит от порядка'],
    ['лишнее чтение можно убрать', 'нет', 'счётчик изменится'],
  ],
);

note(
  'Все четыре предположения — это то, на чём держатся простые оптимизации:',
  'вынести общее подвыражение, поменять порядок вычислений, убрать чтение,',
  'результат которого не нужен. Геттер отменяет каждое из них, потому что за',
  'обращением к свойству стоит вызов функции.',
  '',
  'Вот почему в constant-folding.mjs `MemberExpression` возвращает ⊤ безусловно,',
  'даже когда объект — литерал, объявленный строкой выше. Доказать, что чтение',
  'безопасно, можно только зная, что у объекта и всей его цепочки прототипов нет',
  'геттера с таким именем, — а это знание статически недоступно.',
);

section('Proxy: любая операция может соврать');

const trapped = new Proxy(
  {},
  {
    get: (_target, property) => `перехвачено: ${String(property)}`,
    has: () => true,
    getPrototypeOf: () => Array.prototype,
  },
);

table(
  ['операция', 'обычный объект', 'через Proxy'],
  [
    ['obj.нет_такого', String({}.нет_такого), String(trapped.нет_такого)],
    ["'что угодно' in obj", String('что угодно' in {}), String('что угодно' in trapped)],
    ['Array.isArray(obj)', String(Array.isArray({})), String(Array.isArray(trapped))],
    ['obj instanceof Array', String({} instanceof Array), String(trapped instanceof Array)],
  ],
);

note(
  'Proxy — это возможность перехватить сами примитивные операции языка: чтение',
  'свойства, проверку наличия, получение прототипа, вызов. Для анализатора это',
  'значит, что даже утверждение «у пустого объекта нет свойства `foo`» перестаёт',
  'быть верным.',
  '',
  'Обратите внимание на `instanceof`: он даёт `true`, потому что перехвачено',
  'получение прототипа. `Array.isArray` остался честным — он проверяет внутренний',
  'признак, а не прототип, и подделать его через Proxy нельзя. Такие детали',
  'приходится знать наизусть, если пишешь анализ, которому верят.',
);

section('Прототипы: метод может подмениться после');

class Reader {
  next() {
    return 'из класса';
  }
}

const reader = new Reader();
const beforePatch = reader.next();
Reader.prototype.next = () => 'подменено снаружи';
const afterPatch = reader.next();

table(
  ['когда', 'reader.next()'],
  [
    ['сразу после new', beforePatch],
    ['после записи в Reader.prototype', afterPatch],
  ],
);

note(
  'Объект тот же, метод тот же, результат другой. Для анализа это означает, что',
  '`reader.next()` нельзя заменить на тело метода — то есть нельзя сделать',
  'девиртуализацию и инлайн, на которых в статически типизированных языках',
  'держится половина производительности.',
  '',
  'V8 эту задачу решает, но не анализом: он ставит инлайн-кеш, запоминает,',
  'какой именно метод вызывался, оптимизирует под него — и оставляет проверку.',
  'Как только проверка не сходится (а после записи в прототип она не сойдётся),',
  'происходит деоптимизация. Разбор — разделы 10 и 11.',
);

