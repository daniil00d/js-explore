// Лексический анализ руками: из символов получаются токены — и сразу выясняется,
// что без парсера лексер не работает.
//
// Запуск: node 02-lexing-parsing-ast/examples/tokenize.mjs

import * as acorn from 'acorn';
import { note, section, table, truncate } from '../../tools/format.mjs';
import { tokenize } from './lexer.mjs';

const acornTokens = (source) =>
  [...acorn.tokenizer(source, { ecmaVersion: 'latest' })].map((token) => ({
    label: token.type.label === 'name' ? 'name' : token.type.label,
    value: source.slice(token.start, token.end),
  }));

section('Токены: что видит лексер вместо текста');

const snippet = `const total = items.length * 1_000 + 0xff; // хвостовой комментарий
let label = \`итого: \${total}\`;
if (!ready) label = "нет данных";`;

const { tokens, comments } = tokenize(snippet);

table(
  ['#', 'тип', 'значение', 'строка', 'перенос перед'],
  tokens.map((token, index) => [
    index + 1,
    token.type,
    truncate(token.value, 22),
    token.line,
    token.newlineBefore ? 'да' : '',
  ]),
);

note(
  `Токенов: ${tokens.length}, комментариев: ${comments.length}.`,
  '',
  'Из текста исчезли пробелы и переносы, но не полностью: у каждого токена остался',
  'флаг «перед ним был перенос строки». Без него нельзя реализовать вставку точек',
  'с запятой из раздела 01 — парсер обязан знать, где в исходнике кончалась строка.',
  '',
  'Комментарии тоже не выброшены, а отложены в отдельный список: компилятору они',
  'не нужны, а вот линтеру нужны для директив, а форматтеру — чтобы их не потерять.',
);

section('Почему лексер не бывает независимым от парсера');

const ambiguous = [
  ['деление', 'const ratio = total / count / 2;'],
  ['регулярка после =', 'const re = /ab+c/gi;'],
  ['регулярка после return', 'function f() { return /^\\d+$/.test(s); }'],
  ['регулярка после )', 'if (ready) /^\\d+$/.test(s);'],
  ['регулярка после блока', '{ }\n/^\\d+$/.test(s);'],
];

const classifySlashes = (list, kindOf, valueOf) => {
  const slashes = list.filter((token) => kindOf(token) === 'regexp' || valueOf(token) === '/');
  if (slashes.length === 0) return 'слэшей нет';
  return slashes.map((token) => (kindOf(token) === 'regexp' ? 'регулярка' : 'деление')).join(', ');
};

table(
  ['случай', 'наш лексер', 'acorn'],
  ambiguous.map(([label, code]) => {
    let ours;
    try {
      ours = classifySlashes(tokenize(code).tokens, (t) => t.type, (t) => t.value);
    } catch (error) {
      ours = `сдался: ${truncate(error.message, 30)}`;
    }
    const theirs = classifySlashes(acornTokens(code), (t) => t.label, (t) => t.value);
    return [label, ours, theirs];
  }),
);

note(
  'Первые три строки совпадают: эвристика «после значения — деление, после оператора —',
  'регулярка» работает. На четвёртой она ломается. Закрывающая скобка обычно завершает',
  'значение (`(a + b) / 2`), но в `if (ready) /re/.test(s)` за той же скобкой начинается',
  'инструкция — и там слэш открывает регулярку.',
  '',
  'Различить эти два случая по предыдущему токену невозможно: нужно знать, скобка была',
  'от группировки или от `if`. Поэтому у настоящих лексеров есть стек контекстов, который',
  'пополняет парсер, — в acorn это `tokContext`. Лексер и парсер работают чередуясь,',
  'а не двумя последовательными проходами.',
);

section('Ключевые слова, которых нет в списке ключевых слов');

const parses = (code, sourceType) => {
  try {
    acorn.parse(code, { ecmaVersion: 'latest', sourceType });
    return 'да';
  } catch (error) {
    return truncate(error.message.replace(/\s*\(\d+:\d+\)$/, ''), 30);
  }
};

table(
  ['слово как имя', 'в скрипте', 'в модуле', 'то же слово в роли ключевого'],
  [
    ['var let = 1', 'let x = 1'],
    ['var yield = 1', 'function* g() { yield 1 }'],
    ['var await = 1', 'async function f() { await 1 }'],
    ['var async = 1', 'async function f() {}'],
    ['var of = 1', 'for (const x of []) {}'],
    ['var get = 1', 'const o = { get x() { return 1 } }'],
    ['var from = 1', 'import x from "m"'],
  ].map(([asName, asKeyword]) => [
    asName,
    parses(asName, 'script'),
    parses(asName, 'module'),
    asKeyword,
  ]),
);

note(
  'Полностью зарезервированных слов немного, и список закрыт. Остальные — контекстные:',
  'слово остаётся обычным именем, пока не окажется в определённой позиции. Причём',
  '`let`, `yield` и `await` меняют статус в зависимости от режима: в скрипте это имена,',
  'в модуле (он всегда строгий) — уже нет.',
  '',
  'Для лексера это значит, что делить токены на «ключевое слово» и «имя» во время',
  'сканирования нельзя: решение зависит и от позиции, и от режима, то есть от парсера.',
  'Наш лексер поэтому помечает такие слова как `name`.',
);

section('Чего в токенах не хватает для полной картины');

note(
  'Мини-лексер выше умышленно неполон, и полезно знать, где именно он врёт:',
  '',
  '- Шаблонная строка берётся одним токеном. В реальности `${...}` содержит выражение,',
  '  внутри которого может быть новый шаблон, поэтому шаблоны разбираются с участием',
  '  парсера, а токенов для них несколько.',
  '- Числа приняты слишком широко: `1_000`, `0xff`, `1e5`, `10n` попадут в один токен,',
  '  но и заведомо неверное `0x1_e+` тоже. Проверку валидности делает спецификация,',
  '  а не регулярка.',
  '- Ключевые слова определяются по списку, без учёта режима: `await` вне async-функции',
  '  и `yield` вне генератора — не ключевые слова, а имена.',
  '- Нет ни экранирования в идентификаторах (`\\u0061bc` — это `abc`), ни разбора',
  '  флагов регулярок, ни `#private` полей как отдельного вида имени.',
  '',
  'Смысл упражнения не в том, чтобы дописать это до конца, а в том, чтобы увидеть',
  'границу: там, где нужны контекст и режим, лексер обязан спрашивать парсер.',
);

