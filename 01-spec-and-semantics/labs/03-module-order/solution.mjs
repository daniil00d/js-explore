// Эталонные ответы к лабе «Порядок инициализации модулей».

export const answers = {
  // Верхнеуровневый await не блокирует граф. Модуль slow начинает выполняться,
  // на `await null` прерывается — и управление уходит дальше по списку импортов.
  // Модуль fast успевает выполниться целиком, потом slow дописывает свой хвост,
  // и только когда все зависимости готовы, выполняется тело main.
  tlaOrder: ['slow:start', 'fast', 'slow:end', 'main'],

  // В ESM зависимости выполняются раньше того, кто их импортирует. Точка входа —
  // модуль a, его зависимость b, поэтому первым выполняется b. Его импорт a уже
  // «в процессе», второй раз он не запускается.
  //
  // Дальше самое интересное. Объявление функции в модуле поднимается и
  // инициализируется до выполнения тела, поэтому helperA у b уже есть — работающая
  // функция. А `export const labelA` живёт в TDZ до своей строки, и обращение
  // к нему из b даёт ReferenceError. Разница не в модулях, а в способе объявления.
  esmCycleOrder: [
    'b:start',
    'b видит helperA: function',
    'b видит labelA: ReferenceError',
    'b:end',
    'a:start',
    'a видит helperB: function',
    'a:end',
  ],

  // В CommonJS всё наоборот: первым начинает тот, кого запросили, — a. Дойдя до
  // require('./cycle-b.cjs'), он передаёт управление b, и b получает объект
  // exports модуля a в том виде, в котором он есть прямо сейчас, — то есть пустой.
  // Никакой ошибки не будет: undefined выглядит как «свойства нет».
  //
  // Node на это ругается предупреждением про circular dependency — проверка его
  // приглушает, чтобы не мешало читать вывод.
  cjsCycleOrder: [
    'a:start',
    'b:start',
    'b видит helperA: undefined',
    'b видит labelA: undefined',
    'b:end',
    'a видит helperB: function',
    'a:end',
  ],

  // Динамический import() возвращает промис, даже если модуль лежит рядом на диске
  // и уже разобран. Тело main дочитывается до конца, и только потом, в следующей
  // задаче микроочереди, выполняется child.
  dynamicImportOrder: ['main:start', 'main:end', 'child', 'main:после await'],
};
