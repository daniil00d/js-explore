// Два режима одного языка: что меняет "use strict" и почему это важно для компилятора.
//
// Запуск: node 01-spec-and-semantics/examples/strict-vs-sloppy.mjs
//
// Сам этот файл — модуль, а модули всегда строгие. Поэтому нестрогие фрагменты
// выполняются через node:vm: там код по умолчанию разбирается как обычный скрипт.

import { note, outcome, section, table } from './harness.mjs';

function comparison(rows) {
  table(
    ['что проверяем', 'нестрогий режим', 'строгий режим'],
    rows.map(([label, sloppy, strict]) => [label, outcome(sloppy), outcome(`"use strict"; ${strict}`)]),
  );
}

section('Разное поведение одного и того же кода');

comparison([
  [
    'this в обычном вызове',
    '(function () { return this === globalThis })()',
    '(function () { return this })()',
  ],
  [
    'присваивание необъявленному',
    'function f() { u = 1 } f(); typeof u',
    'function f() { u = 1 } f();',
  ],
  [
    'arguments и параметр связаны',
    'function f(a) { a = 99; return arguments[0] } f(1)',
    'function f(a) { a = 99; return arguments[0] } f(1)',
  ],
  [
    'запись в замороженный объект',
    'const o = Object.freeze({ x: 1 }); o.x = 2; o.x',
    'const o = Object.freeze({ x: 1 }); o.x = 2; o.x',
  ],
  [
    'удаление неудаляемого',
    'delete Object.prototype',
    'delete Object.prototype',
  ],
  [
    'функция, объявленная в блоке',
    '{ function g() {} } typeof g',
    '{ function g() {} } typeof g',
  ],
]);

note(
  'Три верхние строки — это разница в семантике: код собирается в обоих режимах, но',
  'делает разное. Три нижние — разница в «громкости»: нестрогий режим молча',
  'проглатывает неудачную операцию, строгий бросает TypeError.',
);

section('Что в строгом режиме вообще не компилируется');

table(
  ['фрагмент', 'нестрогий режим', 'строгий режим'],
  [
    ['with (o) { x }', 'let o = { x: 5 }; let r; with (o) { r = x } r', 'let o = {}; with (o) {}'],
    ['восьмеричный литерал 010', '010', 'var n = 010'],
    ['delete переменной', 'var v = 1; delete v', 'var v = 1; delete v'],
    ['дубли параметров', 'function f(a, a) {} "ok"', 'function f(a, a) {}'],
    ['eval как имя', 'var eval = 1; "ok"', 'var eval = 1;'],
  ].map(([label, sloppy, strict]) => [label, outcome(sloppy), outcome(`"use strict"; ${strict}`)]),
);

note(
  'Это уже ранние ошибки из предыдущего примера: строгий режим меняет не только',
  'выполнение, но и грамматику. Один и тот же текст в одном режиме — программа,',
  'в другом — синтаксическая ошибка.',
);

section('Кто включает строгий режим сам');

note(
  'Явная директива "use strict" нужна всё реже: строгими по умолчанию являются',
  'ES-модули (любой .mjs и любой файл с import/export), тела классов, а также код',
  'внутри них. Нестрогим остаётся то, что грузится как обычный скрипт: файлы .cjs,',
  '<script> без type="module" и строки, переданные в eval или new Function.',
  '',
  `Проверка прямо здесь: этот файл — модуль, и в нём this === ${String(this)},`,
  `а не globalThis (${String(this === globalThis)}). Директиву никто не писал.`,
);

section('Почему это важно за пределами стиля');

note(
  'Нестрогий режим требует от движка поддерживать конструкции, которые уничтожают',
  'статический анализ: with делает разрешение имён вычисляемым в рантайме, связь',
  'arguments с параметрами превращает простое присваивание в запись сразу в два места,',
  'а неявные глобальные переменные означают, что любая функция может создать новое имя',
  'в глобальной области.',
  '',
  'Поэтому строгий код проще и оптимизировать, и минифицировать: имена локальных',
  'переменных можно переименовывать, параметры — держать в регистрах, а обращения',
  'к именам — разрешать на этапе компиляции. Переход экосистемы на модули дал движкам',
  'этот выигрыш даром: весь современный код строгий по умолчанию.',
);

