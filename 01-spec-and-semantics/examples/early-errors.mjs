// Early Errors: ошибки, которые спецификация требует выбросить до выполнения кода.
//
// Запуск: node 01-spec-and-semantics/examples/early-errors.mjs

import { compile, describeError, inline, note, run, section, table } from './harness.mjs';

function verdict(code, limit = 46) {
  const compiled = compile(code);
  if (!compiled.ok) return describeError(compiled.error, limit);
  const executed = run(code);
  return executed.ok ? 'выполнился без ошибок' : `рантайм: ${describeError(executed.error, limit - 10)}`;
}

section('Что не доживает до выполнения');

const earlyCases = [
  'let x; let x;',
  'var y; let y;',
  'const c;',
  'return 1;',
  'break;',
  '1 = 2;',
  '({ a: 1 } = {});',
  'class C { constructor() {} constructor() {} }',
  'if (true) let x = 1;',
  'label: label: 1;',
  '/(/;',
  '"use strict"; delete x;',
  '"use strict"; var n = 010;',
  '"use strict"; function f(a, a) {}',
  '(a, a) => a;',
  'function f(a, a) {}',
];

table(
  ['фрагмент', 'что говорит движок'],
  earlyCases.map((code) => [inline(code), verdict(code)]),
);

note(
  '`({ a: 1 } = {})` попадает сюда из-за cover grammar: скобочная конструкция сначала',
  'разбирается как литерал объекта и только при виде `=` перечитывается как цель',
  'присваивания. Литерал `1` целью быть не может — отсюда и ошибка.',
  '',
  'Последняя строка — не оплошность примера: в нестрогом коде дубли параметров',
  'разрешены, а в строгом это ранняя ошибка. Один и тот же текст либо компилируется,',
  'либо нет, в зависимости от режима — и решается это до выполнения.',
);

section('Ранняя ошибка отменяет весь файл целиком');

const withPrint = 'console.log("эта строка не напечатается"); let dup; let dup;';
const compiled = compile(withPrint);
run(withPrint);

note(
  `Фрагмент: ${inline(withPrint)}`,
  '',
  `Результат компиляции: ${compiled.ok ? 'успех' : describeError(compiled.error)}`,
  'Выше нет строки «эта строка не напечатается»: до выполнения дело не дошло.',
  '',
  'Это и отличает раннюю ошибку от исключения. Исключение — событие во время работы',
  'программы, его можно поймать. Ранняя ошибка означает, что программы просто нет:',
  'единица компиляции целиком отвергнута, ни одна её инструкция не выполнялась.',
);

section('Что ранней ошибкой не является');

table(
  ['фрагмент', 'что говорит движок'],
  ['неведомая + 1', '(42)()', 'undefined.x', 'const c = 1; c = 2;', '(function r() { return r() })()'].map(
    (code) => [code, verdict(code)],
  ),
);

note(
  'Всё это ошибки времени выполнения, хотя половину из них статический анализатор',
  'находит без запуска. Спецификация требует ровно того, что перечислено в разделах',
  '«Static Semantics: Early Errors», и ни строчкой больше: движок не обязан замечать,',
  'что программа гарантированно упадёт на первой же строке.',
  '',
  'Именно в этот зазор и встраиваются линтеры с системами типов: они ловят то, что',
  'формально корректно с точки зрения грамматики, но заведомо сломано по смыслу.',
);

section('Как это выглядит в спецификации');

note(
  'Ранние ошибки записаны не в алгоритмах выполнения, а в разделах Static Semantics',
  'рядом с грамматикой. Например, для повторных объявлений это правило вида',
  '«It is a Syntax Error if the LexicallyDeclaredNames of StatementList contains any',
  'duplicate entries» — чистая проверка над деревом разбора, без всякого выполнения.',
  '',
  'Такие правила — самый настоящий статический анализ, встроенный прямо в стандарт:',
  'обход дерева, сбор объявленных имён, поиск дубликатов. Ровно то, что в разделе 03',
  'придётся писать руками.',
);

