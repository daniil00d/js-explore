// Модули против скриптов: разный порядок инициализации и разные гарантии для анализа.
//
// Запуск: node 01-spec-and-semantics/examples/modules-vs-scripts.mjs

import { createRequire } from 'node:module';
import { line, note, section } from './harness.mjs';
import { drain, record } from './fixtures/trace.mjs';

const require = createRequire(import.meta.url);
const numbered = (entries) => entries.forEach((entry, index) => line(`${index + 1}.`, entry, 3));

// Node предупреждает о некоторых из показанных ниже ситуаций сам, но делает это
// асинхронно, и текст выпадает в случайном месте вывода. Перехватываем, чтобы
// напечатать рядом с тем, к чему он относится.
const warnings = [];
process.removeAllListeners('warning');
process.on('warning', (warning) => warnings.push(`${warning.name}: ${warning.message}`));

record('modules-vs-scripts.mjs: тело начало работу');

section('Импорты выполняются раньше тела');

numbered(drain());

note(
  'Первым в журнале стоит announce.mjs, хотя его import написан последней строкой',
  'этого файла. Объявления import не выполняются на своём месте: их поднимают, и',
  'до первой инструкции модуля все зависимости уже отработали.',
  '',
  'Это и есть главное отличие от require(), который выполняется ровно там, где',
  'написан. Именно поэтому граф ES-модулей можно построить, не запуская код.',
);

section('Цикл зависимостей в ES-модулях');

await import('./fixtures/cycle-a.mjs');
numbered(drain());

note(
  'Запрошен был a.mjs, а первым отработал b.mjs: сначала выполняются зависимости.',
  'Внутри цикла b обращается к ещё не выполненному a — и разница между двумя видами',
  'объявлений видна отчётливо.',
  '',
  'Функция fromA доступна: объявления функций инициализируются при создании среды',
  'модуля, до выполнения тела. А valueFromA лежит в TDZ и обращение к ней бросает',
  'ReferenceError — та же механика, что и внутри одной функции, только через границу',
  'модуля.',
);

section('Тот же цикл на CommonJS');

const cjsTrace = require('./fixtures/trace.cjs');
require('./fixtures/cycle-a.cjs');
numbered(cjsTrace.drain());
await new Promise((resolve) => setImmediate(resolve));

note(
  'Порядок обратный: a.cjs начал первым, потому что require() сработал внутри его',
  'тела. Но интереснее другое — b.cjs получил из a пустой объект и undefined вместо',
  'значения, и никакой ошибки при этом не было.',
  '',
  'ESM в такой ситуации бросает исключение, CommonJS молча отдаёт полуготовый объект',
  'экспортов. Отсюда старая порода багов «в проде undefined, а локально всё работает»:',
  'результат зависит от того, какой модуль в цикле загрузили первым.',
  '',
  'Node это место всё-таки замечает и предупреждает:',
  ...warnings.map((warning) => `  ${warning}`),
);

section('Живые привязки против копий');

const live = await import('./fixtures/live.mjs');
line('ESM: counter до bump()', live.counter);
live.bump();
live.bump();
line('ESM: counter после двух bump()', live.counter);

const cjsLive = require('./fixtures/live.cjs');
const { counter: destructured } = cjsLive;
line('CJS: копия до bump()', destructured);
cjsLive.bump();
cjsLive.bump();
line('CJS: та же копия после', destructured);
line('CJS: чтение через объект', cjsLive.counter);

note(
  'import создаёт привязку к переменной в модуле-источнике, а не копию значения:',
  'counter обновился сам. В CommonJS экспортируется обычный объект, поэтому',
  'деструктуризация делает снимок и он больше никогда не изменится.',
  '',
  'Для сборщика это принципиально: живые привязки известны статически, их можно',
  'проследить по графу и выбросить неиспользованные. Свойства объекта exports —',
  'обычные динамические поля, про которые в общем случае доказать ничего нельзя.',
);

section('Верхний уровень: this и режим');

line('в модуле this', String(this));
const cjsThis = require('./fixtures/top-level-this.cjs');
line('в .cjs this === module.exports', cjsThis.isModuleExports);
line('в .cjs this === globalThis', cjsThis.isGlobal);

note(
  'Модуль всегда строгий, его this на верхнем уровне — undefined, а объявления не',
  'попадают в глобальный объект. Скрипт нестрогий по умолчанию, this равен',
  'module.exports в Node (или window в браузерном <script>), а var на верхнем уровне',
  'создаёт глобальное свойство.',
  '',
  'Отсюда, кстати, растёт совет «оборачивай скрипт в IIFE», который стал не нужен',
  'ровно в тот момент, когда файл стал модулем.',
);

section('Что из этого следует для инструментов');

note(
  'Список импортов модуля — статическая информация: имена известны до выполнения,',
  'порядок инициализации определён спецификацией, повторное выполнение невозможно.',
  'На этом стоит весь раздел 07: tree shaking, склейка модулей, деление на чанки.',
  '',
  'require() — обычный вызов функции с произвольным аргументом. Его можно завернуть в',
  'условие, вычислить путь в рантайме, подменить кеш модулей. Граф в этом случае',
  'достраивается только во время работы программы, и сборщику остаётся либо',
  'угадывать, либо тащить в бандл всё подряд.',
);

console.log();

// Объявление специально оставлено в самом низу: оно всё равно выполнится первым.
import './fixtures/announce.mjs';
