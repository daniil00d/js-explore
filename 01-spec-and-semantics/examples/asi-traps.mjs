// Автоматическая вставка точек с запятой: где перенос строки меняет смысл программы.
//
// Запуск: node 01-spec-and-semantics/examples/asi-traps.mjs

import { inline, note, outcome, section, table } from './harness.mjs';

section('Три правила из спецификации');

note(
  'ASI — часть разбора, а не «мелочь про стиль». Правил ровно три:',
  '',
  '1. Токен не лезет в грамматику, и перед ним есть перенос строки — вставить точку',
  '   с запятой перед ним.',
  '2. Дошли до конца файла, а программа не разобралась — вставить точку с запятой',
  '   в конце.',
  '3. Ограниченные продукции (restricted productions): после return, throw, break,',
  '   continue, ++, --, yield и перед => перенос запрещён — точка с запятой',
  '   вставляется немедленно.',
  '',
  'Ключевое следствие первого правила: точка с запятой вставляется, только если без',
  'неё разбор невозможен. Если следующая строка может продолжить выражение — она его',
  'продолжит, и никакого переноса для парсера не существует.',
);

section('Строка продолжается, хотя выглядит самостоятельной');

table(
  ['фрагмент', 'что получилось'],
  [
    ['let x = a + b\n(c).toString()', outcome('let a = 1, b = 2, c = 3;\nlet x = a + b\n(c).toString()\nx')],
    ['let y = arr\n[0]', outcome('let arr = [10, 20];\nlet y = arr\n[0]\ny')],
    ['let z = f\n`шаблон`', outcome('let f = () => "вызвали как тег";\nlet z = f\n`шаблон`\nz')],
    ['let c = a\n-b', outcome('let a = 1, b = 2;\nlet c = a\n-b\nc')],
    ['let r = g\n/foo/g.test("x")', outcome('let g = 6, foo = 2;\nlet r = g\n/foo/g.test("x")\nr')],
  ].map(([code, result]) => [inline(code), result]),
);

note(
  'Шесть символов, с которых нельзя начинать строку без точки с запятой в конце',
  'предыдущей: (, [, `, +, -, /. Первые три превращают предыдущее выражение в вызов,',
  'индексацию и тегированный шаблон, последние три — в бинарную операцию.',
  '',
  'Отсюда и обычай ставить точку с запятой в начале строки (;[1, 2].forEach(...)) в',
  'кодовых базах без точек с запятой: она нужна не для красоты, а чтобы разорвать',
  'выражение.',
);

section('Ограниченные продукции: перенос решает всё');

table(
  ['фрагмент', 'что получилось'],
  [
    ['return\n42', outcome('(function () {\n  return\n  42\n})()')],
    ['return\n{ a: 1 }', outcome('(function () {\n  return\n  { a: 1 }\n})()')],
    ['n\n++\nm', outcome('let n = 1, m = 5;\nn\n++\nm\n[n, m]')],
    ['continue\nouter;', outcome('let hits = 0;\nouter: for (let i = 0; i < 3; i++) { continue\nouter; hits++ }\nhits')],
    ['yield\n1', outcome('function* g() { yield\n1 }\n[...g()]')],
    ['throw\nnew Error()', outcome('throw\nnew Error("сообщение")')],
    ['(a)\n=> a', outcome('let g = (a)\n=> a')],
  ].map(([code, result]) => [inline(code), result]),
);

note(
  'Первые пять случаев — молчаливые: программа собирается и работает, просто делает',
  'не то. `return` возвращает undefined, `continue` игнорирует метку, генератор отдаёт',
  'undefined вместо единицы. Последние два хотя бы падают на разборе.',
  '',
  'Случай с `n ⏎ ++ ⏎ m` стоит разобрать целиком: ASI обрывает строку после n, дальше',
  'идёт `++m`, а следующая строка `[n, m]` не начинает новое выражение, а индексирует',
  'результат. Получается ++m[n, m] — обращение по индексу с оператором «запятая»',
  'внутри, то есть m[3]. Итог — NaN там, где ждали пару чисел.',
);

section('Где ASI не спасает никогда');

table(
  ['фрагмент', 'что получилось'],
  [[inline('for (let i = 0\ni < 2\ni++) {}'), outcome('for (let i = 0\ni < 2\ni++) {}\n"дошли до конца"')]],
);

note(
  'Внутри заголовка for точки с запятой обязательны: спецификация прямо запрещает',
  'вставлять их как разделители в этой позиции. Такое же исключение — пустая',
  'инструкция: `while (cond)` с переносом не превращается в `while (cond);`.',
);

section('Что из этого следует');

note(
  'ASI — не постобработка текста, а часть работы парсера: он пытается разобрать поток',
  'токенов и вставляет точку с запятой только когда упирается. Поэтому «ставить или не',
  'ставить точки с запятой» — вопрос не вкуса, а знания списка исключений.',
  '',
  'Практический вывод для инструментов: Prettier и подобные форматтеры печатают код',
  'заново из дерева и расставляют точки с запятой сами, поэтому в форматированном',
  'проекте эти ловушки просто не возникают. А вот кодмод, который вставляет строки в',
  'исходный текст без разбора, легко их создаёт — ещё один довод в пользу того, чтобы',
  'править AST, а не текст.',
);

