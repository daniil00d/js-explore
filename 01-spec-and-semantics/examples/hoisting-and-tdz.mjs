// Подъём объявлений и временная мёртвая зона: что происходит до первой строки кода.
//
// Запуск: node 01-spec-and-semantics/examples/hoisting-and-tdz.mjs

import { line, note, outcome, section, table } from './harness.mjs';

section('Один и тот же код, три вида объявлений');

table(
  ['объявление', 'чтение до строки объявления'],
  [
    ['var x = 1', outcome('(function () { const seen = x; var x = 1; return seen; })()')],
    ['let y = 1', outcome('(function () { const seen = y; let y = 1; return seen; })()')],
    ['const z = 1', outcome('(function () { const seen = z; const z = 1; return seen; })()')],
    ['function f() {}', outcome('(function () { return f(); function f() { return "вызвалась"; } })()')],
    ['var g = function () {}', outcome('(function () { return g(); var g = function () {}; })()')],
    ['class C {}', outcome('(function () { return new C(); class C {} })()')],
  ],
);

note(
  'Подняты все шесть: имена известны до выполнения тела. Разница в том, чем они',
  'проинициализированы. var получает undefined, функция — готовую функцию, а let,',
  'const и class остаются непроинициализированными: это и есть TDZ.',
);

section('Почему TDZ — не «переменной ещё нет»');

table(
  ['выражение', 'результат'],
  [
    ['typeof неизвестноеИмя', outcome('typeof неизвестноеИмя')],
    ['typeof x до let x = 1', outcome('typeof x; let x = 1;')],
    ['let q = q', outcome('let q = q;')],
    ['{ let b = 1; } typeof b', outcome('{ let b = 1; } typeof b')],
  ],
);

note(
  'typeof — единственная операция, которой разрешено не бросать на необъявленном имени.',
  'На имени в TDZ она бросает, потому что имя объявлено: анализатор его видит, просто',
  'значение ещё не положили. Отсюда и разные сообщения: «is not defined» против',
  '«Cannot access ... before initialization».',
);

section('TDZ в параметрах по умолчанию');

table(
  ['функция', 'вызов без аргументов'],
  [
    ['function h(a = b, b = 2)', outcome('function h(a = b, b = 2) { return a } h()')],
    ['function h(b = 2, a = b)', outcome('function h(b = 2, a = b) { return a } h()')],
  ],
);

note(
  'Список параметров — это тоже область видимости со своим порядком инициализации.',
  'Значения по умолчанию вычисляются слева направо, и левый параметр не видит правый.',
);

section('Одна переменная на цикл или новая на каждую итерацию');

line('var i, три замыкания', outcome('let out = []; for (var i = 0; i < 3; i++) out.push(() => i); out.map((f) => f())'));
line('let i, три замыкания', outcome('let out = []; for (let i = 0; i < 3; i++) out.push(() => i); out.map((f) => f())'));

note(
  'С var переменная одна на всю функцию, и все замыкания смотрят в неё же.',
  'С let спецификация создаёт новую привязку на каждую итерацию и копирует в неё',
  'значение предыдущей — CreatePerIterationEnvironment в алгоритме ForBodyEvaluation.',
);

section('Что из этого следует для анализа');

note(
  'Подъём — не причуда, а следствие того, что среда создаётся до выполнения кода:',
  'сначала обходятся объявления и создаются привязки, потом исполняются инструкции.',
  'Поэтому область видимости можно построить статически, одним проходом по дереву,',
  'и именно это делают и линтер, и минификатор, и сам движок.',
  '',
  'TDZ ломает одно удобное упрощение: наличие привязки больше не означает, что к ней',
  'можно обратиться. Проверка «инициализирована ли» остаётся на рантайм, и компилятор',
  'обязан её вставлять, пока не докажет обратное.',
);

